def main():
    # Augmented Assignment Operator
    score = 10
    score+=10
    print(score)

    # Substraction Assignment Operator
    # x -= y
    grade = 100
    grade -= 10
    print(grade)

    # Multiplication Assignmanet Operator
    balance = 10
    balance *= 4
    print(balance)

    # Division Assignment Operator
    x = 10
    x /=5
    print(int(x))

    # Modulus Assignment Operator
    a = 10
    b = 4

    a %= b
    print(a)

if __name__=="__main__":
    main()

